void Add(std::string* s, const char* fmt, ...) {
  char buf[512];
  va_list ap;
  va_start(ap, fmt);
  std::vsnprintf(buf, sizeof buf, fmt, ap);
  va_end(ap);
  *s += buf;
}

const char* StageName(HackStage k) { return k == HackStage::Path ? "path" : k == HackStage::Rhythm ? "rhythm" : "frequency"; }

